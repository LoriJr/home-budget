CREATE TABLE bills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    due_date DATE NOT NULL,
    bill_category VARCHAR(30) NOT NULL,
    bill_status VARCHAR(30) NOT NULL,
    paid_amount NUMERIC(12, 2),
    paid_at DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_bills_amount_positive
        CHECK (amount > 0),

    CONSTRAINT chk_bills_paid_amount_non_negative
        CHECK (paid_amount IS NULL OR paid_amount >= 0),

    CONSTRAINT chk_bills_paid_amount_limit
        CHECK (paid_amount IS NULL OR paid_amount <= amount),

    CONSTRAINT chk_bills_category
        CHECK (bill_category IN (
            'WATER',
            'ELECTRICITY',
            'INTERNET',
            'HOUSING',
            'FOOD',
            'TRANSPORT',
            'SUBSCRIPTIONS',
            'OTHER'
        )),

    CONSTRAINT chk_bills_status
        CHECK (bill_status IN (
            'PENDING',
            'PAID',
            'CANCELLED'
        ))
);

CREATE INDEX idx_bills_due_date
    ON bills (due_date);

CREATE INDEX idx_bills_status
    ON bills (bill_status);

CREATE INDEX idx_bills_category
    ON bills (bill_category);